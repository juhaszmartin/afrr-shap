"""Writes entsoe_availability.md: the input series that survive preprocessing, per country and category.
Run after scripts/preprocess_all.py: python scripts/get_entsoe_info.py"""

import re
from collections import defaultdict
from pathlib import Path

import polars as pl

from afrr_shap.config import TEST_START, TIME_FEATURES
from afrr_shap.paths import PROCESSED_DIR

LAG_SUFFIX = re.compile(r"_t[+-]\d+(min|h)$")
WEATHER = ("temperature", "ssrd", "wind_speed")
CATEGORIES = [
    "target history",
    "activated_balancing_energy_prices",
    "procured_balancing_capacity",
    "contracted_reserve_amount",
    "contracted_reserve_prices",
    "prices",
    "load",
    "load_forecast",
    "generation",
    "generation_forecast",
    "wind_and_solar_forecast",
    "intraday_wind_and_solar_forecast",
    "import",
    "net_position",
    "weather",
    "calendar",
]


def series_by_category(columns):
    """Base series (value at t, without lags and leads) per category."""
    out = defaultdict(set)
    for c in columns:
        if c == "timestamp":
            continue
        if c in TIME_FEATURES:
            out["calendar"].add(re.sub(r"_(sin|cos)$", "", c))
        elif c.startswith("imbalance_"):
            out["target history"].add(LAG_SUFFIX.sub("", c))
        elif LAG_SUFFIX.search(c):
            continue  # every lagged series also appears at t
        elif any(w in c for w in WEATHER):
            out["weather"].add(c)
        else:
            cat, _, name = c.partition(" - ")
            out[cat].add(name)
    return out


def format_timestamp(value):
    """Format UTC timestamps without repeating the timezone in every cell."""
    return "-" if value is None else value.replace(tzinfo=None).isoformat(sep=" ")


if __name__ == "__main__":
    data = {}
    for f in sorted(PROCESSED_DIR.glob("X_*.parquet")):
        cc = Path(f).stem.split("_")[1]
        timestamps = pl.read_parquet(f, columns=["timestamp"])["timestamp"]
        has_training_data = timestamps.lt(TEST_START).any()
        has_test_data = timestamps.ge(TEST_START).any()
        if has_training_data and has_test_data:
            status = "usable"
        elif has_test_data:
            status = "excluded: no training data"
        elif has_training_data:
            status = "excluded: no test data"
        else:
            status = "excluded: empty processed data"
        data[cc] = (
            series_by_category(pl.read_parquet_schema(f)),
            [c for c in pl.read_parquet_schema(PROCESSED_DIR / f"y_{cc}.parquet")],
            {
                "rows": timestamps.len(),
                "first": timestamps.min(),
                "last": timestamps.max(),
                "has_training": has_training_data,
                "has_test": has_test_data,
                "status": status,
            },
        )
    countries = list(data)
    eligible_countries = [
        cc for cc in countries if data[cc][2]["status"] == "usable"
    ]
    cats = [
        c
        for c in CATEGORIES
        if any(c in data[cc][0] for cc in eligible_countries)
    ]
    cats += sorted(
        {
            c
            for cc in eligible_countries
            for c in data[cc][0]
        }
        - set(cats)
    )

    lines = [
        "# Input series per country\n\n",
        (
            "Generated by `scripts/get_entsoe_info.py` from `data/processed/` after preprocessing, so it lists only the "
            "series that survive the column filters (PIPELINE.md §4). Each series enters the model at t and with its "
            "lags and leads (PIPELINE.md §5). Calendar sin/cos pairs count as one series.\n\n"
        ),
        "## Data availability\n\n",
        "| Country | Processed samples | First timestamp (UTC) | Last timestamp (UTC) | Training data | 2025 test data | Status |\n",
        "|---|---:|---|---|---|---|---|\n",
    ]
    for cc in countries:
        availability = data[cc][2]
        lines.append(
            f"| {cc} | {availability['rows']} | "
            f"{format_timestamp(availability['first'])} | "
            f"{format_timestamp(availability['last'])} | "
            f"{'yes' if availability['has_training'] else 'no'} | "
            f"{'yes' if availability['has_test'] else 'no'} | "
            f"{availability['status']} |\n"
        )
    lines.extend(
        [
            "\n",
            "## Number of series\n\n",
            "| Category | " + " | ".join(eligible_countries) + " |\n",
            "|---|" + "---|" * len(eligible_countries) + "\n",
        ]
    )
    for cat in cats:
        lines.append(
            f"| {cat} | "
            + " | ".join(
                str(len(data[cc][0].get(cat, ()))) or "0"
                for cc in eligible_countries
            )
            + " |\n"
        )
    lines.append("\n")
    for cc in eligible_countries:
        series, targets, _ = data[cc]
        lines.append(f"## {cc}\n\n")
        lines.append(f"Targets: {', '.join(f'`{t}`' for t in targets)}\n\n")
        for cat in cats:
            if cat in series:
                lines.append(
                    f"- **{cat}**: "
                    + ", ".join(f"`{s}`" for s in sorted(series[cat]))
                    + "\n"
                )
        lines.append("\n")
    Path("entsoe_availability.md").write_text("".join(lines))
    print(f"wrote entsoe_availability.md for {len(countries)} countries")
